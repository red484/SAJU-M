export const SECTIONS = ['사주 관점', '현실 확인', '오늘 할 일'];
// 제목은 줄 맨 앞에 그대로 서 있어야 합니다. 본문 속에 우연히 같은 말이
// 섞인 경우를 제목으로 세지 않도록 줄 시작만 봅니다.
const head = h => new RegExp('^\\s*' + h + '\\s*$', 'm');
export const hasSections = (text, turn = 1) => {
  const need = turn >= 2 ? SECTIONS.slice(1) : SECTIONS;
  const value = String(text);
  return new RegExp(`^[ \\t]*${need[0]}[ \\t]*(?:\\r?\\n|$)`).test(value)
    && need.every(h => head(h).test(value));
};
// 본문에 새면 안 되는 명리 용어. '상관없다'의 상관, '~편인데'의 편인,
// '일주일간'의 일간처럼 일상어와 겹치는 것은 앞뒤를 보고 거릅니다.
const JARGON = [
  /(?<![주일])일간(?![호])|일주(?!일)|월주|년주|시주|원국|명식/g,
  /갑목|을목|병화|정화|무토|기토|경금|신금|임수|계수/g,
  /[목화토금수]\s*기운|오행|십성|십이운성|신살|지장간|대운|일진|세운|천간|지지(?!하|해|했|받|층|율|도|자|선)/g,
  /비견|겁재|식신|편재|정재|편관|정관|편인(?![데지가])|(?<![예일결])정인(?![데지가])/g,
  /상관(?!없|있|관계|자|도)/g,
  /도화(?!선|지)|역마|화개|공망|천을귀인|장생|건록|제왕(?!절개)/g,
  /삼합|육합|상충|합충/g];
export const jargonLeaks = text => [...new Set(JARGON.flatMap(re => String(text).match(re) || []))];

// 물러서는 말끝. 어조 규칙이 '담담하고 서늘하게'인데 이런 맺음이 쌓이면 정반대가 됩니다.
const HEDGE = /것이 좋습니다|것도 방법입니다|볼 수 있습니다|수도 있습니다|때입니다|듯합니다|같습니다/g;
// 진료 권유는 한 문장이면 충분합니다. 검사 항목까지 들면 우리가 할 말이 아닙니다.
const MEDICAL = /건강\s*검진|혈액\s*검사|검사\s*결과|진단|처방|약을|영양제/g;
// 모델의 자체 점검이나 시스템 지시가 본문으로 새는 경우입니다.
const META = /추가\s*확인|준수\)|글자\s*수\s*제한|필수\s*제목|입력된\s*계산값|규칙\s*설명|자체\s*평가|를\s*붙이세요/g;
const UNSUPPORTED = /어려운\s*시기로|주변의\s*(?:기대|시선)|마음이\s*무겁|몸도?\s*지쳐|피로로\s*이어|눈을\s*붙여|걷기\s*운동|목\s*스트레칭|심호흡|혼자(?:서)?[^.!?\n]{0,30}(?:감당|고민|애쓰|속앓이)|타고나기|강인함|스스로를[^.!?\n]{0,20}지치|그\s*일\s*때문에/g;

// 답을 되돌려주기 전에 스스로 읽어 봅니다. 걸린 것이 있으면 무엇이 걸렸는지
// 짚어서 한 번만 다시 받습니다. 프롬프트에 적어두는 것만으로는 지켜지지 않습니다.
export function critique(raw, basis, turn = 1) {
  const text = stripBasis(raw);
  const out = [];
  // 첫 답변은 세 제목, 후속 답변은 두 제목. 후속에서 사주 관점을 또 펼치면
  // 같은 해석을 매 턴 되풀이하게 되므로 그것도 지적합니다.
  const need = turn >= 2 ? SECTIONS.slice(1) : SECTIONS;
  const missing = need.filter(h => !head(h).test(text));
  if (missing.length) out.push(`${need.map(h => `"${h}"`).join(', ')} 제목이 각각 한 줄에 그대로 있어야 합니다. 빠진 것: ${missing.join(', ')}.`);
  if (turn >= 2 && head(SECTIONS[0]).test(text)) out.push('후속 답변에는 "사주 관점" 제목을 다시 쓰지 않습니다. 해석은 첫 답변에서 한 번만 펼칩니다.');
  const leaks = jargonLeaks(text);
  if (leaks.length) out.push(`명리 용어 ${leaks.join('·')}이(가) 본문에 그대로 나왔습니다. 그 말이 뜻하는 장면을 사람이 하는 행동으로 옮겨 적으세요.`);
  if (!basis) out.push('<근거> 블록이 없습니다. 사주 관점을 쓸 때 명식에서 실제로 읽은 값을 적어야 합니다.');
  const med = text.match(MEDICAL) || [];
  if (med.length) out.push(`검사 항목이나 진단 이야기(${[...new Set(med)].join('·')})는 빼세요. 이어지면 진료로 확인하라는 한 문장까지입니다.`);
  const meta = [...new Set(text.match(META) || [])];
  if (meta.length) out.push(`내부 지시나 자체 점검(${meta.join('·')})이 본문에 노출되었습니다.`);
  const unsupported = [...new Set(text.match(UNSUPPORTED) || [])];
  if (unsupported.length) out.push(`사용자가 말하지 않은 원인이나 건강 행동(${unsupported.join('·')})을 만들었습니다.`);
  const hedge = [...new Set(text.match(HEDGE) || [])];
  if (hedge.length >= 3) out.push(`맺음이 흐립니다(${hedge.join('·')}). '~하세요', '~입니다'로 끊으세요.`);
  return out;
}

export async function coachReply({ chart: rawChart, messages: rawMessages }) {
  const chart = readChart(rawChart);
  if (!chart) return { error: '명식 정보가 없습니다.', status: 400 };

  const turns = list(rawMessages, 8, m =>
    m && (m.role === 'user' || m.role === 'assistant') && typeof m.text === 'string'
      ? { role: m.role, content: m.text.slice(0, 800) }
      : null);
  while (turns.length && turns[0].role !== 'user') turns.shift();
  if (!turns.length || turns.at(-1).role !== 'user') return { error: '보낼 메시지가 없습니다.', status: 400 };

  // 위기·의료·재무 질문은 모델에 보내지 않고 기존 안전 응답을 그대로 씁니다.
  const safe = safety(turns.at(-1).content);
  if (safe) return { text: safe, source: 'safety' };

  const base = [{ role: 'system', content: realtimeSystemPrompt(chart) }, ...turns];
  // 모바일 상담은 첫 응답 시간을 우선합니다. 규칙 답은 이미 화면에 있으므로
  // AI가 20초 안에 끝내지 못하면 즉시 폴백을 유지합니다.
  const deadlineAt = Date.now() + 20_000;
  let res = await chatCompletion({
    messages: base,
    // Gemini 2.5 Flash는 내부 추론 토큰도 completion 사용량에 포함합니다.
    // 700에서는 본문을 쓰기 전에 상한에 닿을 수 있어, 짧은 출력 지시는
    // 유지하면서 추론 여유만 확보합니다.
    maxTokens: 1200,
    temperature: 0.35,
    metadata: { feature: 'coach' },
    continueOnLength: false,
    deadlineAt
  });
  // 형식 보정을 위한 두 번째 LLM 호출은 최악의 대기 시간을 크게 늘립니다.
  // 검증만 수행하고 어긋난 답은 즉시 규칙 코칭으로 넘깁니다.
  const turn = chart.turnIndex;
  const faults = critique(res.text, readBasis(res.text), turn);
  const basis = readBasis(res.text);
  const shape = { model: res.model, keyLabel: res.keyLabel, usage: res.usage, finishReason: res.finishReason, truncated: res.truncated,
    continuations: res.continuations, turn, sections: hasSections(res.text, turn), leaks: jargonLeaks(stripBasis(res.text)), faults: faults.length, basis };
  if (shape.truncated) return { error: 'AI 답변이 생성 중에 끊겼습니다.', status: 502, shape };
  if (!shape.sections) return { error: '답변 형식이 어긋났습니다.', status: 502, shape };
  if (faults.length) return { error: 'AI 답변이 품질 검사를 통과하지 못했습니다.', status: 502, shape };

  let text = res.text;
  // 모델이 붙인 기록 제안 블록을 본문에서 떼어내 구조화합니다. 형식이
  // 어긋나면 조용히 버립니다 — 본문은 그대로 읽히므로 손해가 없습니다.
  let offer = null;
  text = text.replace(/<기록>([\s\S]*?)<\/기록>/g, (_, body) => {
    try {
      const o = JSON.parse(body);
      const title = str(o.title, 60).trim();
      if (title && TOPICS.includes(o.topic)) offer = { title, topic: o.topic, expectation: str(o.expectation, 300).trim() };
    } catch { /* 형식이 어긋나면 제안 없이 넘어갑니다 */ }
    return '';
  }).trim();
  text = stripBasis(text);
  if (!text) return { error: '빈 응답을 받았습니다.', status: 502, shape };
  return { text, offer, source: 'cafe24', usage: res.usage, shape };
}
